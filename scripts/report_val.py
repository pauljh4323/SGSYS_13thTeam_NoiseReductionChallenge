"""Write docs/validation_results.md for the submitted config from scripts/eval.py per-file CSVs.

Reads outputs/<config>/eval_<split><suffix>.csv (default suffix "_pred" = scored main.py outputs,
as written by `eval.py --pred-dir`). Noisy-input metrics come from the same rows
(noisy = enhanced - delta), so both columns are from one eval run. No metric is computed here.
"""
from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import pandas as pd

from _common import REPO_ROOT, git_hash, load_config


def load(cfg_name: str, split: str, suffix: str) -> tuple[pd.DataFrame, Path]:
    path = REPO_ROOT / "outputs" / cfg_name / f"eval_{split}{suffix}.csv"
    if not path.is_file():
        raise FileNotFoundError(f"{path} missing: run scripts/eval.py --split {split} first")
    df = pd.read_csv(path)
    df["pesq_noisy"] = df.pesq - df.delta_pesq
    df["snr_noisy"] = df.snr_db - df.delta_snr_db
    return df, path


def z(v: float, nd: int = 2) -> float:
    """Round and drop the sign of zero (no '-0.00')."""
    return round(float(v), nd) + 0.0


def table(df: pd.DataFrame, by: str | None, label: str) -> str:
    groups = [("overall", df)] if by is None else [
        (f"{k:g} dB" if by == "target_snr_db" else str(k), g)
        for k, g in df.groupby(by, sort=True)]
    if by == "noise_difficulty":
        order = {"easy": 0, "moderate": 1, "hard": 2}
        groups.sort(key=lambda kg: order.get(kg[0], 9))
    lines = [f"| {label} | n | PESQ noisy | PESQ {{m}} | ΔPESQ | SNR noisy (dB) | SNR {{m}} (dB) | ΔSNR (dB) |",
             "|---|---|---|---|---|---|---|---|"]
    for key, g in groups:
        lines.append(f"| {key} | {len(g)} | {g.pesq_noisy.mean():.4f} | {g.pesq.mean():.4f} | "
                     f"{g.delta_pesq.mean():+.4f} | {z(g.snr_noisy.mean()):.2f} | {z(g.snr_db.mean()):.2f} | "
                     f"{z(g.delta_snr_db.mean()):+.2f} |")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=str(REPO_ROOT / "configs" / "submission.yaml"))
    parser.add_argument("--suffix", default="_pred",
                        help='eval CSV suffix: "_pred" (main.py outputs, default) or "" (in-memory 16-bit)')
    parser.add_argument("--out", default=str(REPO_ROOT / "docs" / "validation_results.md"))
    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    val, val_path = load(cfg["name"], "validation", args.suffix)
    rmx, rmx_path = load(cfg["name"], "val_remix", args.suffix)
    for name, df in (("validation", val), ("val_remix", rmx)):
        if df.pesq.isna().any():
            raise RuntimeError(f"{name}: {int(df.pesq.isna().sum())} PESQ failures; fix before reporting")
    m = cfg["method"]
    params = ", ".join(f"{k}={v}" for k, v in cfg["params"].items())
    rel = lambda p: p.relative_to(REPO_ROOT).as_posix()  # noqa: E731
    text = f"""# Validation results — submitted version

Generated by `scripts/report_val.py` on {date.today().isoformat()} at git `{git_hash()}`.

- Config: `configs/{cfg['name']}.yaml` — method `{m}` ({params})
- Scored files: 16-bit WAVs written by `main.py` (eval.py `--pred-dir`), PESQ-WB `pesq==0.0.4` at 16 kHz, SNR = course definition.
- Sources: `{rel(val_path)}`, `{rel(rmx_path)}` (per-file rows; noisy = enhanced − delta, same run). Experiment rows: `results/experiments.csv`.
- validation: official split (164 files, 5 speakers). val_remix: 328 remixes of validation clean speech with other validation noises (seed 1234), a secondary held-out check that is never used for selection.

## Validation — overall

{table(val, None, "set").replace("{m}", m)}

## Validation — per target SNR

{table(val, "target_snr_db", "target SNR").replace("{m}", m)}

## Validation — per noise difficulty

{table(val, "noise_difficulty", "difficulty").replace("{m}", m)}

## val_remix — overall

{table(rmx, None, "set").replace("{m}", m)}
"""
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} (validation PESQ {val.pesq.mean():.4f} SNR {val.snr_db.mean():.2f} dB; "
          f"val_remix PESQ {rmx.pesq.mean():.4f} SNR {rmx.snr_db.mean():.2f} dB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
